#!/usr/bin/env bash
# Synthetic, public-safe 30 s test clip for talkinghead.
#
# Speech is generated with macOS `say` (espeak-ng elsewhere) and separated by generated silence; the
# picture is ffmpeg's testsrc2 at 1280x720, 30 fps. Output: H.264 video and AAC
# audio, both exactly 30 s long. The script checks the ffprobe durations of the
# streams and fails if they differ by more than 0.05 s.
#
# Usage: scripts/make_demo_clip.sh OUTPUT.mp4
# Needs macOS `say` or espeak-ng (apt install espeak-ng on Linux), plus ffmpeg and ffprobe on PATH.
set -euo pipefail

if [ "$#" -ne 1 ]; then
  echo "usage: $0 OUTPUT.mp4" >&2
  exit 2
fi
out=$1
dur=30
pause=1.2

lines=(
  "This is a synthetic test clip. Nobody is speaking about anything real."
  "It has a few pauses, so silence detection has something to find."
  "Each sentence is generated by the text to speech engine, then joined with silence."
  "That is the end of the test clip."
)

ext=aiff
if [ "$(uname -s)" != Darwin ]; then
  command -v espeak-ng >/dev/null 2>&1 || { echo "espeak-ng not found: apt install espeak-ng" >&2; exit 2; }
  ext=wav
fi
speak() {
  if [ "$ext" = aiff ]; then say -o "$2" "$1"; else espeak-ng -w "$2" "$1"; fi
}

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

inputs=()
parts=()
for i in "${!lines[@]}"; do
  speak "${lines[$i]}" "$work/s$i.$ext"
  inputs+=(-i "$work/s$i.$ext")
  parts+=("[$i:a]aresample=48000,aformat=sample_fmts=fltp:channel_layouts=mono[s$i]")
  if [ "$i" -lt $(( ${#lines[@]} - 1 )) ]; then
    parts+=("aevalsrc=0:s=48000:d=$pause:c=mono,aformat=sample_fmts=fltp:channel_layouts=mono[p$i]")
  fi
done

concat_in=""
for i in "${!lines[@]}"; do
  concat_in+="[s$i]"
  if [ "$i" -lt $(( ${#lines[@]} - 1 )) ]; then
    concat_in+="[p$i]"
  fi
done
count=$(( ${#lines[@]} * 2 - 1 ))
parts+=("${concat_in}concat=n=${count}:v=0:a=1,apad=whole_dur=${dur},atrim=end=${dur},aformat=channel_layouts=stereo[aout]")
parts+=("testsrc2=size=1280x720:rate=30:duration=${dur},format=yuv420p[vout]")

filter=$(IFS=';'; echo "${parts[*]}")

ffmpeg -v error -y "${inputs[@]}" -filter_complex "$filter" \
  -map "[vout]" -map "[aout]" -t "$dur" \
  -c:v libx264 -preset medium -crf 20 -pix_fmt yuv420p \
  -c:a aac -b:a 128k -ar 48000 -movflags +faststart "$out"

probe() {
  ffprobe -v error -select_streams "$1" -show_entries stream=duration -of csv=p=0 "$out"
}
v_dur=$(probe v:0)
a_dur=$(probe a:0)
if ! awk -v v="$v_dur" -v a="$a_dur" -v d="$dur" \
  'BEGIN { ok = (v - a < 0.05 && a - v < 0.05 && v - d < 0.05 && d - v < 0.05); exit !ok }'; then
  echo "duration mismatch: video ${v_dur}s audio ${a_dur}s, expected ${dur}s" >&2
  exit 1
fi
echo "wrote $out (video ${v_dur}s, audio ${a_dur}s)"
